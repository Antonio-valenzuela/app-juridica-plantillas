import { readFile, writeFile } from 'node:fs/promises';
const cases=['contestacion','apelacion','amparo','penal'];
const summary=[];
for (const id of cases) {
  const dir=`audit/final-pre-windows-readiness/controlled-cases/${id}`;
  const journey=JSON.parse(await readFile(`${dir}/journey.json`,'utf8'));
  const doc=JSON.parse(await readFile(`${dir}/produced-document.json`,'utf8'));
  const trace=doc.generationMetadata.auditTrace;
  journey.DOCUMENT_PLAN=trace.documentPlanSnapshot;
  journey.GENERATION_TASKS=trace.generationTasks;
  journey.QUALITY_GATE=trace.qualityGateResult;
  journey.LEGAL_RESEARCH=trace.legalResearch || {status:'NO_OFFICIAL_AUTHORITY_VERIFIED_IN_OFFLINE_SCOPE'};
  // Summary uses existing generated bytes only: no further provider/pipeline request.
  journey.legalQualityStatus='FAIL_NOT_CERTIFIED';
  await writeFile(`${dir}/journey.json`,JSON.stringify(journey,null,2));
  summary.push({case:id,classification:journey.classification,sections:doc.sections.length,
    words:doc.sections.flatMap(s=>s.content.map(b=>b.text)).join(' ').split(/\s+/).filter(Boolean).length,
    planSections:trace.documentPlanSnapshot?.sections?.length ?? 0,tasks:trace.generationTasks.length,
    finalStatus:doc.status,readiness:doc.generationMetadata.readiness,qualityGatePassed:trace.qualityGateResult.passed,
    manualVersion:doc.generationMetadata.operationalManual?.manualVersion,
    manualSelectedRules:doc.generationMetadata.operationalManual?.selectedRuleIds?.length||0,
    manualAuditFindings:doc.generationMetadata.operationalManual?.auditFindings?.length||0,
    exports:journey.exports,legalQualityStatus:journey.legalQualityStatus});
}
await writeFile('audit/final-pre-windows-readiness/controlled-cases-summary.json',JSON.stringify(summary,null,2));
console.log(JSON.stringify(summary,null,2));
