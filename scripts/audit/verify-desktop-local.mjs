import { launchDesktopLocal, assertPortAvailable } from '../desktop/local-launcher.mjs';
import { createHash } from 'node:crypto';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
const root = process.cwd();
const dir = join(root, 'audit/desktop-local-boundary-2026-09-29');
await mkdir(dir, {recursive:true});
const frozen = ['lib/legal-engine/qualityGate.ts','lib/legal-engine/documentCoverage.ts','lib/security/lawyerAuth.ts','lib/cases/access.ts','lib/operational-manual/core.ts'];
const hashes = async () => Object.fromEntries(await Promise.all(frozen.map(async path => [path, createHash('sha256').update(await readFile(join(root,path))).digest('hex')])));
const before = await hashes();
const logs = [];
const report = { startedAt: new Date().toISOString(), frozenBefore: before, status: 'FAIL' };
let session;
try {
  session = await launchDesktopLocal({projectDir:root, port:3200, development:true, onOutput:line => logs.push(line)});
  const headers = {'x-lex-desktop-capability':session.capability};
  const metadata = await fetch(`${session.baseUrl}/api/operational-manual`, {headers});
  report.metadataStatus = metadata.status;
  assert.equal(metadata.status,200);
  const data = await metadata.json();
  assert.equal(data.manifest.version,'1.0'); assert.equal(data.manifest.pageCount,212); assert.equal(data.manifest.fragmentCount,6860);
  report.manifest = {version:data.manifest.version,pageCount:data.manifest.pageCount,fragmentCount:data.manifest.fragmentCount};
  const pdf = await fetch(`${session.baseUrl}/api/operational-manual/original`, {headers});
  report.pdfStatus = pdf.status;
  report.pdfContentType = pdf.headers.get('content-type');
  assert.equal(pdf.status,200); assert.equal(pdf.headers.get('content-type'),'application/pdf');
  report.pdfSha256 = createHash('sha256').update(new Uint8Array(await pdf.arrayBuffer())).digest('hex');
  assert.equal(report.pdfSha256,'b3910bb8a0b44bd1a38d3fe9edbd32984ade48b6b66c7bf62b01db3e79348f25');
  report.missingCapabilityStatus = (await fetch(`${session.baseUrl}/api/operational-manual`)).status;
  report.invalidCapabilityStatus = (await fetch(`${session.baseUrl}/api/operational-manual`, {headers:{'x-lex-desktop-capability':'a'.repeat(64)}})).status;
  assert.equal(report.missingCapabilityStatus,403); assert.equal(report.invalidCapabilityStatus,403);
  const exchanged = await fetch(`${session.baseUrl}/api/desktop-local/session`, {method:'POST',headers});
  assert.equal(exchanged.status,204);
  report.exchangeStatus = exchanged.status;
  const cookieHeader = exchanged.headers.get('set-cookie');
  report.cookie = { httpOnly: /(?:^|;)\s*httponly(?:;|$)/i.test(cookieHeader), sameSiteStrict: /(?:^|;)\s*samesite=strict(?:;|$)/i.test(cookieHeader), scopedToManual: /path=\/api\/operational-manual(?:;|$)/i.test(cookieHeader) };
  assert.ok(Object.values(report.cookie).every(Boolean));
  const cookie = cookieHeader.split(';')[0];
  report.cookieManualStatus = (await fetch(`${session.baseUrl}/api/operational-manual`,{headers:{cookie}})).status;
  assert.equal(report.cookieManualStatus,200);
  const netstat = execFileSync('netstat',['-ano','-p','tcp'],{encoding:'utf8'});
  report.listener = netstat.split(/\r?\n/).filter(line => /:3200\s/.test(line) && /LISTENING/.test(line));
  assert.ok(report.listener.some(line => /127\.0\.0\.1:3200/.test(line)));
  assert.ok(report.listener.every(line => !/0\.0\.0\.0:3200|\[::\]:3200/.test(line)));
  const oldCapability = session.capability;
  report.secretAbsentFromUrl = !session.baseUrl.includes(oldCapability);
  await session.close(); session = undefined;
  await assertPortAvailable(3200); report.shutdownPortClosed = true;
  session = await launchDesktopLocal({projectDir:root, port:3200, development:true, onOutput:line => logs.push(line)});
  report.restartCapabilityDifferent = session.capability !== oldCapability;
  assert.ok(report.restartCapabilityDifferent);
  report.oldCapabilityAfterRestartStatus = (await fetch(`${session.baseUrl}/api/operational-manual`, { headers: {'x-lex-desktop-capability':oldCapability} })).status;
  report.oldCookieAfterRestartStatus = (await fetch(`${session.baseUrl}/api/operational-manual`,{headers:{cookie}})).status;
  report.newCapabilityAfterRestartStatus = (await fetch(`${session.baseUrl}/api/operational-manual`,{headers:{'x-lex-desktop-capability':session.capability}})).status;
  assert.equal(report.oldCapabilityAfterRestartStatus,403); assert.equal(report.oldCookieAfterRestartStatus,403); assert.equal(report.newCapabilityAfterRestartStatus,200);
  const newCapability = session.capability;
  await session.close(); session = undefined;
  await assertPortAvailable(3200); report.restartShutdownPortClosed = true;
  report.secretAbsentFromLogs = logs.every(line => !line.includes(oldCapability) && !line.includes(newCapability));
  assert.ok(report.secretAbsentFromLogs);
  report.status = 'PASS';
} catch (error) { report.error = error.code ?? error.message; process.exitCode = 1; }
finally {
  if (session) await session.close();
  report.frozenAfter = await hashes();
  assert.deepEqual(report.frozenAfter,before);
  report.frozenUnchanged = true;
  await writeFile(join(dir,'runtime-verification.json'),JSON.stringify(report,null,2));
  await writeFile(join(dir,'runtime-verification.log'),logs.join('\n'));
  console.log(JSON.stringify(report,null,2));
}
